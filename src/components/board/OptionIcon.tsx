/**
 * The icon a person picked for an option, in the colour of what holds it.
 * Decorative: the name beside it, or the tooltip, says which value it is.
 */
export function OptionIcon({
  name,
  size = 12,
  className,
  color,
}: {
  name: IconName;
  size?: number;
  className?: string;
  color?: string;
}) {
  const Icon = ICON_OF[name];
  if (!Icon) return null;
  return (
    <Icon
      aria-hidden="true"
      focusable="false"
      width={size}
      height={size}
      strokeWidth={2.5}
      className={className}
      style={color ? { color, flexShrink: 0 } : { flexShrink: 0 }}
      data-icon={name}
    />
  );
}
